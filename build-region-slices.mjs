#!/usr/bin/env node
// build-region-slices.mjs — emit per-metro slices of the proprietary data files for licensing
// tiers. A demo/metro account's requests for the statewide files are rewritten by
// functions/_middleware.js to these sliced variants, so the gating is server-side and real —
// the full statewide dataset never reaches a metro-licensed browser.
//
//   node build-region-slices.mjs          # writes *-dfw.js next to the originals
//
// Slices: pe-data.js (PE_COORDS by bbox; PE_NAMES kept whole — it's the national brand list
// checkPE needs for name matching, not a Texas asset), vet-clinics.js (rows by bbox),
// vet-staff.js + vet-species.js (cell-keyed: key = round(lat*1000)_round(lon*1000)).
import fs from 'node:fs';

const REGIONS = { dfw: { s: 32.25, n: 33.5, w: -97.95, e: -96.2 } };

function sliceAll(regionKey, bb) {
  const inBB = (la, lo) => la >= bb.s && la <= bb.n && lo >= bb.w && lo <= bb.e;
  const cellIn = k => { const m = String(k).match(/^(-?\d+)_(-?\d+)$/); if (!m) return false; return inBB(+m[1] / 1000, +m[2] / 1000); };

  // pe-data.js
  {
    const raw = fs.readFileSync('pe-data.js', 'utf8');
    const ni = raw.indexOf('{'), ne = raw.indexOf('};');
    const names = raw.slice(ni, ne + 1);
    const ci = raw.indexOf('PE_COORDS=');
    const coords = JSON.parse(raw.slice(ci + 'PE_COORDS='.length, raw.lastIndexOf(']') + 1));
    const kept = coords.filter(c => inBB(c[0], c[1]));
    fs.writeFileSync(`pe-data-${regionKey}.js`,
      `// Auto-generated by build-region-slices.mjs — ${regionKey.toUpperCase()} slice (${kept.length}/${coords.length} PE clinics). Do not edit; re-run the script.\n` +
      `window.PE_NAMES=${names};\nwindow.PE_COORDS=${JSON.stringify(kept)};\nif(typeof onPEReady==='function')onPEReady();\n`);
    console.log(`pe-data-${regionKey}.js: ${kept.length}/${coords.length} clinics`);
  }
  // vet-clinics.js
  {
    const raw = fs.readFileSync('vet-clinics.js', 'utf8');
    const i = raw.lastIndexOf('window.VET_CLINICS'), j = raw.indexOf('[', i), k = raw.lastIndexOf(']');
    const all = JSON.parse(raw.slice(j, k + 1));
    const kept = all.filter(c => inBB(c.lat, c.lon));
    fs.writeFileSync(`vet-clinics-${regionKey}.js`,
      `// Auto-generated by build-region-slices.mjs — ${regionKey.toUpperCase()} slice (${kept.length}/${all.length} clinics). Do not edit; re-run the script.\n` +
      `window.VET_CLINICS=${JSON.stringify(kept)};\n`);
    console.log(`vet-clinics-${regionKey}.js: ${kept.length}/${all.length} clinics`);
  }
  // vet-staff.js + vet-species.js (cell-keyed objects)
  for (const [file, varName] of [['vet-staff.js', 'VET_STAFF'], ['vet-species.js', 'VET_SPECIES']]) {
    if (!fs.existsSync(file)) { console.log(`${file}: absent, skipped`); continue; }
    const raw = fs.readFileSync(file, 'utf8');
    const ai = raw.indexOf('window.' + varName + '=');           // skip header comments (they contain braces)
    const i = raw.indexOf('{', ai), k = raw.lastIndexOf('}');
    const all = JSON.parse(raw.slice(i, k + 1));
    const out = {};
    let n = 0, total = 0;
    for (const key of Object.keys(all)) { total++; if (cellIn(key)) { out[key] = all[key]; n++; } }
    const base = file.replace('.js', '');
    fs.writeFileSync(`${base}-${regionKey}.js`,
      `// Auto-generated by build-region-slices.mjs — ${regionKey.toUpperCase()} slice (${n}/${total} entries). Do not edit; re-run the script.\n` +
      `window.${varName}=${JSON.stringify(out)};\n`);
    console.log(`${base}-${regionKey}.js: ${n}/${total} entries`);
  }
}

for (const [key, bb] of Object.entries(REGIONS)) sliceAll(key, bb);
console.log('done');
